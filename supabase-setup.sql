-- RAJIV TG BOTS — Supabase database setup
-- Run this entire script in Supabase Dashboard > SQL Editor.
-- Safe to run again: tables/indexes/policies are created conditionally.

create extension if not exists pgcrypto;

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.bot_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  enabled boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now()
);

create table if not exists public.bots (
  id uuid primary key default gen_random_uuid(),
  name varchar(80) not null,
  username varchar(64) not null,
  category text not null default 'Other',
  description varchar(500) not null,
  tags text[] not null default '{}',
  image_url text,
  image_path text,
  status text not null default 'active' check (status in ('active','maintenance')),
  featured boolean not null default false,
  is_public boolean not null default true,
  clicks bigint not null default 0 check (clicks >= 0),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint bots_username_unique unique (username)
);

create index if not exists bots_public_created_idx on public.bots(is_public,created_at desc);
create index if not exists bots_category_idx on public.bots(category);
create index if not exists bots_name_search_idx on public.bots using gin(to_tsvector('simple',name || ' ' || username || ' ' || description));

insert into public.bot_categories(name,sort_order) values
 ('AI',1),('Utility',2),('Entertainment',3),('Games',4),('Moderation',5),
 ('Giveaway',6),('Music',7),('Other',99)
on conflict(name) do nothing;

create or replace function public.is_directory_admin()
returns boolean language sql stable security definer set search_path=public
as $$
  select exists(select 1 from public.admins where user_id=auth.uid());
$$;

revoke all on function public.is_directory_admin() from public;
grant execute on function public.is_directory_admin() to authenticated;

alter table public.admins enable row level security;
alter table public.bot_categories enable row level security;
alter table public.bots enable row level security;

drop policy if exists "admins read own row" on public.admins;
create policy "admins read own row" on public.admins for select to authenticated
using (user_id=auth.uid() or public.is_directory_admin());

drop policy if exists "categories public read" on public.bot_categories;
create policy "categories public read" on public.bot_categories for select to anon,authenticated using (enabled=true or public.is_directory_admin());
drop policy if exists "categories admin manage" on public.bot_categories;
create policy "categories admin manage" on public.bot_categories for all to authenticated
using(public.is_directory_admin()) with check(public.is_directory_admin());

drop policy if exists "public reads public bots" on public.bots;
create policy "public reads public bots" on public.bots for select to anon,authenticated using(is_public=true);
drop policy if exists "admin reads all bots" on public.bots;
create policy "admin reads all bots" on public.bots for select to authenticated using(public.is_directory_admin());
drop policy if exists "admin inserts bots" on public.bots;
create policy "admin inserts bots" on public.bots for insert to authenticated with check(public.is_directory_admin());
drop policy if exists "admin updates bots" on public.bots;
create policy "admin updates bots" on public.bots for update to authenticated using(public.is_directory_admin()) with check(public.is_directory_admin());
drop policy if exists "admin deletes bots" on public.bots;
create policy "admin deletes bots" on public.bots for delete to authenticated using(public.is_directory_admin());

-- Public images, private upload permissions. Do not store sensitive files here.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('bot-images','bot-images',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict(id) do update set public=true,file_size_limit=5242880,allowed_mime_types=array['image/jpeg','image/png','image/webp'];

drop policy if exists "public can view bot images" on storage.objects;
create policy "public can view bot images" on storage.objects for select to anon,authenticated
using(bucket_id='bot-images');
drop policy if exists "admins upload bot images" on storage.objects;
create policy "admins upload bot images" on storage.objects for insert to authenticated
with check(bucket_id='bot-images' and public.is_directory_admin());
drop policy if exists "admins update bot images" on storage.objects;
create policy "admins update bot images" on storage.objects for update to authenticated
using(bucket_id='bot-images' and public.is_directory_admin())
with check(bucket_id='bot-images' and public.is_directory_admin());
drop policy if exists "admins delete bot images" on storage.objects;
create policy "admins delete bot images" on storage.objects for delete to authenticated
using(bucket_id='bot-images' and public.is_directory_admin());

-- Allow the website to receive live changes when a bot listing changes.
do $$
begin
  if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='bots') then
    alter publication supabase_realtime add table public.bots;
  end if;
exception when undefined_object then null;
end $$;

